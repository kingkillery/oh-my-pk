"""Deterministic MCP config synchronizer.

Reads canonical root `.mcp.json` and writes deterministic UTF-8 LF
configs to IDE-specific targets (Cursor, Windsurf, VS Code, Codex).

Usage:
    python .agents/scripts/sync_mcp_configs.py
    python .agents/scripts/sync_mcp_configs.py --check
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

CANONICAL = ".mcp.json"
JSON_TARGETS: tuple[str, ...] = (
    ".cursor/mcp.json",
    ".windsurf/mcp.json",
    ".windsurf/mcp_config.json",
    ".vscode/mcp.json",
)
TOML_TARGET = ".codex/config.toml"


def repo_root() -> Path:
    """Return repository root (two levels above this script)."""
    return Path(__file__).resolve().parents[2]


def load_servers(root: Path) -> dict[str, Any]:
    """Load `mcpServers` mapping from canonical `.mcp.json`."""
    data: Any = json.loads((root / CANONICAL).read_text(encoding="utf-8"))
    servers: dict[str, Any] = data.get("mcpServers", {})
    if not isinstance(servers, dict):
        raise TypeError("mcpServers must be an object")
    # Deep-copy via JSON round-trip so sorting never mutates the source.
    return json.loads(json.dumps(servers, sort_keys=True))


def dumps_json(payload: Any) -> bytes:
    """Serialize payload deterministically as UTF-8 LF JSON bytes."""
    text: str = json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False)
    return (text + "\n").encode("utf-8")


def _toml_string(value: str) -> str:
    """Render a string as a TOML basic string (JSON-compatible escaping)."""
    return json.dumps(value, ensure_ascii=False)


def _toml_value(value: Any) -> str:
    """Render a JSON-derived value as TOML inline value."""
    if isinstance(value, str):
        return _toml_string(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        inner: str = ", ".join(_toml_value(v) for v in value)
        return "[" + inner + "]"
    if isinstance(value, dict):
        inner_d: str = ", ".join(
            _toml_string(str(k)) + " = " + _toml_value(v)
            for k, v in sorted(value.items(), key=lambda item: str(item[0]))
        )
        return "{ " + inner_d + " }" if inner_d else "{}"
    if value is None:
        return _toml_string("")
    return _toml_string(str(value))


def render_toml(servers: dict[str, Any]) -> bytes:
    """Render deterministic Codex `config.toml` bytes for `servers`."""
    lines: list[str] = [
        "# Codex MCP configuration — generated by sync_mcp_configs.py.",
        "# Do not edit by hand; edit canonical root .mcp.json and re-run",
        "# `python .agents/scripts/sync_mcp_configs.py`.",
        "# On Windows, grant read access to the shell that launches the",
        "# MCP server (pwsh / powershell) so it can load this file and the",
        "# stdio server script. Keep .agents/ rules, context, and scripts",
        "# readable from that shell (see .agents/instructions.md).",
        "",
    ]
    for name in sorted(servers):
        server: dict[str, Any] = servers[name]
        lines.append("[mcp_servers." + name + "]")
        for key in ("command", "args"):
            if key in server:
                lines.append(key + " = " + _toml_value(server[key]))
        lines.append("")
        env: Any = server.get("env")
        if isinstance(env, dict) and env:
            lines.append("[mcp_servers." + name + ".env]")
            for env_key in sorted(env):
                lines.append(env_key + " = " + _toml_value(env[env_key]))
            lines.append("")
    text: str = "\n".join(lines)
    if not text.endswith("\n"):
        text += "\n"
    return text.encode("utf-8")


def build_targets(servers: dict[str, Any]) -> dict[str, bytes]:
    """Build deterministic bytes for every sync target."""
    cursor: Any = {"mcpServers": servers}
    windsurf: Any = {"mcpServers": servers}
    windsurf_cfg: Any = {"mcpServers": servers}
    vscode: Any = {"servers": servers, "mcp": {"servers": servers}}
    return {
        ".cursor/mcp.json": dumps_json(cursor),
        ".windsurf/mcp.json": dumps_json(windsurf),
        ".windsurf/mcp_config.json": dumps_json(windsurf_cfg),
        ".vscode/mcp.json": dumps_json(vscode),
        TOML_TARGET: render_toml(servers),
    }


def write_targets(root: Path, targets: dict[str, bytes]) -> list[str]:
    """Write all targets deterministically; return written relative paths."""
    written: list[str] = []
    for rel in sorted(targets):
        path: Path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(targets[rel])
        written.append(rel)
    return written


def check_targets(root: Path, targets: dict[str, bytes]) -> list[str]:
    """Return drift details for targets not matching canonical bytes."""
    drift: list[str] = []
    for rel in sorted(targets):
        path: Path = root / rel
        if not path.exists():
            drift.append(rel + ": missing (not generated)")
            continue
        actual: bytes = path.read_bytes()
        if actual != targets[rel]:
            drift.append(rel + ": drift (content differs from canonical)")
    return drift


def main(argv: list[str] | None = None) -> int:
    """Entry point: sync IDE MCP configs from canonical `.mcp.json`."""
    parser: argparse.ArgumentParser = argparse.ArgumentParser(
        description="Sync IDE MCP configs from canonical .mcp.json"
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify synced files match canonical .mcp.json byte-for-byte",
    )
    args = parser.parse_args(argv)
    root: Path = repo_root()
    servers: dict[str, Any] = load_servers(root)
    targets: dict[str, bytes] = build_targets(servers)
    if args.check:
        drift: list[str] = check_targets(root, targets)
        if drift:
            print("MCP configs out of sync:", file=sys.stderr)
            for entry in drift:
                print(" - " + entry, file=sys.stderr)
            return 1
        print("MCP configs in sync: " + ", ".join(sorted(targets)))
        return 0
    written: list[str] = write_targets(root, targets)
    print("Wrote MCP targets: " + ", ".join(written))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
